export const DEFAULT_PRESET = 'bookman';

export function presetById(id?: string | null): BotPreset {
  return BOT_PRESETS.find((p) => p.id === id) ?? BOT_PRESETS.find((p) => p.id === DEFAULT_PRESET)!;
}

